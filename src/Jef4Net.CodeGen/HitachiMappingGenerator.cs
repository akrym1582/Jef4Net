using System.Globalization;
using System.Text;
using System.Text.Json;

namespace Jef4Net.CodeGen;

internal static class HitachiMappingGenerator
{
    internal static string Generate(string dataDirectory)
    {
        var output = new StringBuilder("// <auto-generated />\nnamespace Jef4Net.Hitachi.Internal;\n\ninternal static class HitachiTables\n{\n");
        foreach (var definition in new[]
        {
            (File: "hitachi_ebcdic_mapping.json", Name: "Ebcdic", Size: 256),
            (File: "hitachi_ebcdik_mapping.json", Name: "Ebcdik", Size: 256),
            (File: "hitachi_keis78_mapping.json", Name: "Keis78", Size: 65536),
            (File: "hitachi_keis83_mapping.json", Name: "Keis83", Size: 65536),
        })
        {
            using var document = JsonDocument.Parse(File.ReadAllText(Path.Combine(dataDirectory, definition.File)));
            var decode = new ulong[definition.Size];
            var encode = new SortedDictionary<ulong, int>();
            var decodedKeys = new ulong[definition.Size];
            foreach (JsonElement record in document.RootElement.EnumerateArray())
            {
                int code = Parse(record.GetProperty("code"));
                int scalar = Parse(record.GetProperty("unicode"));
                if ((uint)code >= definition.Size || scalar > 0x10FFFF || scalar is >= 0xD800 and <= 0xDFFF)
                    throw new InvalidDataException($"Invalid mapping in {definition.File}.");
                string[] options = record.GetProperty("options").EnumerateArray().Select(x => x.GetString()!).ToArray();
                if (options.Except(new[] { "compatible", "decode_only", "combination" }).Any())
                    throw new InvalidDataException($"Unknown option in {definition.File}.");
                ulong key = (ulong)(scalar + 1) << 21;
                if (decode[code] != 0 && decode[code] != key)
                {
                    // The pinned upstream EBCDIC data assigns 8F to both U+FF88 and U+FF89.
                    // Preserve its last-record decode selection, but do not emit an encoder
                    // entry for the displaced scalar because that entry cannot round-trip.
                    bool knownEbcdic8FConflict = definition.File == "hitachi_ebcdic_mapping.json" &&
                        code == 0x8F && decodedKeys[code] == ((ulong)(0xFF88 + 1) << 21) &&
                        key == ((ulong)(0xFF89 + 1) << 21);
                    if (!knownEbcdic8FConflict)
                        throw new InvalidDataException($"Conflicting decode {code:X4} in {definition.File}.");
                    encode.Remove(decodedKeys[code]);
                }
                decode[code] = key;
                decodedKeys[code] = key;
                if (!options.Contains("decode_only")) encode[key] = code; // upstream JSON order wins
            }

            Emit(definition.Name + "Decode", "ulong", decode.Select(x => x.ToString(CultureInfo.InvariantCulture) + "UL"));
            Emit(definition.Name + "Keys", "ulong", encode.Keys.Select(x => x.ToString(CultureInfo.InvariantCulture) + "UL"));
            Emit(definition.Name + "Codes", "ushort", encode.Values.Select(x => x.ToString(CultureInfo.InvariantCulture)));
        }

        output.Append("}\n");
        return output.ToString();

        static int Parse(JsonElement value) => int.Parse(value.GetString()!, NumberStyles.HexNumber, CultureInfo.InvariantCulture);
        void Emit(string name, string type, IEnumerable<string> entries)
        {
            output.Append($"    internal static System.ReadOnlySpan<{type}> {name} => new {type}[]\n    {{\n");
            int index = 0;
            foreach (string value in entries)
            {
                if (index % 16 == 0) output.Append("        ");
                output.Append(value).Append(',').Append(++index % 16 == 0 ? '\n' : ' ');
            }
            if (index % 16 != 0) { output.Length--; output.Append('\n'); }
            output.Append("    };\n");
        }
    }
}
